params AS (
  SELECT
    CAST(CURRENT_DATE - INTERVAL '30' DAY AS TIMESTAMP) AS window_start,
    CAST(CURRENT_DATE AS TIMESTAMP) AS window_end
),
b AS (
  SELECT
    tin,
    rb_user_id,
    CAST(source_location_id AS INTEGER) AS source_location_id,
    CAST(destination_location_id AS INTEGER) AS destination_location_id,
    date_of_journey,
    time_of_event
  FROM transaction.bus_ticket_events
  CROSS JOIN params p
  WHERE event_type = 101
    AND country_code = 'IND'
    AND rb_user_id IS NOT NULL
    AND time_of_event >= p.window_start
    AND time_of_event < p.window_end
),
