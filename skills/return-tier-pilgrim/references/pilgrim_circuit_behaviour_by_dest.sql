  i.group_label,
  i.index_dest AS dest_id,
  pd.dest_name,
  COUNT(DISTINCT i.index_tin) AS index_bookings,
  COUNT(DISTINCT i.rb_user_id) AS index_users,
  ROUND(100.0 * COUNT(DISTINCT CASE WHEN i.has_return_72h = 1 THEN i.rb_user_id END)
    / NULLIF(COUNT(DISTINCT i.rb_user_id), 0), 2) AS return_user_pct_72h,
  ROUND(100.0 * COUNT(DISTINCT CASE WHEN i.has_same_circuit_72h = 1 THEN i.rb_user_id END)
    / NULLIF(COUNT(DISTINCT i.rb_user_id), 0), 2) AS same_circuit_user_pct_72h,
  ROUND(100.0 * COUNT(DISTINCT CASE WHEN i.has_other_onward_72h = 1 THEN i.rb_user_id END)
    / NULLIF(COUNT(DISTINCT i.rb_user_id), 0), 2) AS other_onward_user_pct_72h
FROM next_hops i
INNER JOIN pilgrim_dest pd ON i.index_dest = pd.dest_id
GROUP BY 1, 2, 3
HAVING COUNT(DISTINCT i.index_tin) >= 50
ORDER BY same_circuit_user_pct_72h DESC
LIMIT 80;
