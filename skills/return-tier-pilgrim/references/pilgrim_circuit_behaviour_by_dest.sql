next_hops AS (
  SELECT
    i.group_label,
    i.rb_user_id,
    i.tin AS index_tin,
    i.destination_location_id AS index_dest,
    MAX(CASE WHEN t2.destination_location_id = i.source_location_id THEN 1 ELSE 0 END) AS has_return_72h,
    MAX(CASE
          WHEN t2.destination_location_id <> i.source_location_id
           AND cp.peer_dest_id IS NOT NULL
          THEN 1 ELSE 0 END) AS has_same_circuit_72h,
    MAX(CASE
          WHEN t2.destination_location_id <> i.source_location_id
           AND cp.peer_dest_id IS NULL
          THEN 1 ELSE 0 END) AS has_other_onward_72h
  FROM index_trips i
  LEFT JOIN b t2
    ON t2.rb_user_id = i.rb_user_id
   AND t2.source_location_id = i.destination_location_id
   AND t2.time_of_event > i.time_of_event
   AND ABS(DATE_DIFF('hour', i.date_of_journey, t2.date_of_journey)) <= 72
  LEFT JOIN circuit_peers cp
    ON cp.dest_id = i.destination_location_id
   AND cp.peer_dest_id = t2.destination_location_id
  GROUP BY 1, 2, 3, 4
)
