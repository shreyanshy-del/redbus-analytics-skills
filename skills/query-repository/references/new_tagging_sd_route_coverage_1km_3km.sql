events AS (
  SELECT
    TRY_CAST(b.src_location_id AS BIGINT)         AS source_id,
    TRY_CAST(b.destination_location_id AS BIGINT) AS destination_id,
    b.route_id,
    TRY_CAST(b.dropping_point_id AS BIGINT)       AS dropping_point_id
  FROM transaction.bus_ticket_events b
  WHERE b.date_of_issue >= TIMESTAMP '2026-06-11 00:00:00'
    AND b.date_of_issue <  TIMESTAMP '2026-06-18 00:00:00'
    AND b.route_id IS NOT NULL
    AND b.dropping_point_id IS NOT NULL
    AND b.country_code = 'IND'
    AND b.event_type = 101
    AND b.event_class = 2
),

scoped AS (
  SELECT
    e.source_id,
    e.destination_id,
    e.route_id,
    e.dropping_point_id
  FROM events e
  INNER JOIN sd_pairs_ids sp
    ON e.source_id = sp.source_id
   AND e.destination_id = sp.destination_id
),

-- One row per SD + route_id: did this route use any near-POI dropping point?
sd_route_flags AS (
  SELECT
    s.source_id,
    s.destination_id,
    s.route_id,
    MAX(CASE WHEN db.bucket = 'Less than 1' THEN 1 ELSE 0 END) AS has_1km_bp,
    MAX(CASE WHEN db.bucket IN ('Less than 1', 'Between 1-3') THEN 1 ELSE 0 END) AS has_3km_bp
  FROM scoped s
  LEFT JOIN dp_buckets db
    ON s.dropping_point_id = db.dropping_point_id
  GROUP BY s.source_id, s.destination_id, s.route_id
),

sd_route_agg AS (
  SELECT
    source_id,
    destination_id,
    COUNT(*)        AS total_routes_sd,
    SUM(has_1km_bp) AS routes_within_1km_sd,
    SUM(has_3km_bp) AS routes_within_3km_sd
  FROM sd_route_flags
  GROUP BY source_id, destination_id
),

-- Transaction share: each event row counts as one transaction on that SD
sd_txn_agg AS (
  SELECT
    s.source_id,
    s.destination_id,
    COUNT(*) AS total_txns_sd,
    SUM(CASE WHEN db.bucket = 'Less than 1' THEN 1 ELSE 0 END) AS txns_within_1km_sd,
    SUM(CASE WHEN db.bucket IN ('Less than 1', 'Between 1-3') THEN 1 ELSE 0 END) AS txns_within_3km_sd
  FROM scoped s
  LEFT JOIN dp_buckets db
    ON s.dropping_point_id = db.dropping_point_id
  GROUP BY s.source_id, s.destination_id
),

loc AS (
  SELECT CAST(id AS BIGINT) AS location_id, location_name
  FROM lis.config_locations
  WHERE location_type = 'CITY'
    AND is_expired = 0
)

SELECT
  r.source_id,
  src.location_name AS source_city,
  r.destination_id,
  dst.location_name AS destination_city,

  -- Route coverage (denominator = distinct route_ids on this SD pair)
  r.total_routes_sd,
  r.routes_within_1km_sd,
  r.routes_within_3km_sd,
  ROUND(100.0 * r.routes_within_1km_sd / NULLIF(r.total_routes_sd, 0), 2) AS coverage_pct_1km_sd,
  ROUND(100.0 * r.routes_within_3km_sd / NULLIF(r.total_routes_sd, 0), 2) AS coverage_pct_3km_sd,

  -- Transaction share (denominator = all booking event rows on this SD pair)
  t.total_txns_sd,
  t.txns_within_1km_sd,
  t.txns_within_3km_sd,
  ROUND(100.0 * t.txns_within_1km_sd / NULLIF(t.total_txns_sd, 0), 2) AS txn_share_pct_1km_sd,
  ROUND(100.0 * t.txns_within_3km_sd / NULLIF(t.total_txns_sd, 0), 2) AS txn_share_pct_3km_sd

FROM sd_route_agg r
LEFT JOIN sd_txn_agg t
  ON r.source_id = t.source_id
 AND r.destination_id = t.destination_id
LEFT JOIN loc src
  ON src.location_id = r.source_id
LEFT JOIN loc dst
  ON dst.location_id = r.destination_id
ORDER BY
  r.destination_id,
  r.total_routes_sd DESC,
  r.source_id;
