base AS (
    SELECT
        CAST(b.time_of_event + INTERVAL '330' MINUTE AS DATE) AS event_date_ist,
        b.source_location,
        b.destination_location,
        CAST(b.source_location_id AS BIGINT) AS source_location_id,
        CAST(b.destination_location_id AS BIGINT) AS destination_location_id,
        CAST(b.operator_id AS BIGINT) AS operator_id,
        b.tin,
        b.seat_count,
        b.ticket_fare,
        b.hft,
        u.age,
        u.gender_class,
        u.age_segment,
        TRY_CAST(
            json_extract_scalar(CAST(b.offer_split_list AS VARCHAR), '$.RB_SL_OFFER')
            AS DOUBLE
        ) AS rb_sl_offer
    FROM transaction.bus_ticket_events b
    INNER JOIN target_routes r
        ON CAST(b.source_location_id AS BIGINT) = r.source_location_id
       AND CAST(b.destination_location_id AS BIGINT) = r.destination_location_id
    INNER JOIN target_operators o
        ON CAST(b.operator_id AS BIGINT) = o.operator_id
    INNER JOIN svoc_users u
        ON CAST(b.rb_user_id AS BIGINT) = u.rb_user_id
    WHERE b.event_class = 2
      AND b.event_type = 101
      AND b.country_code = 'IND'
      AND b.time_of_event >= CAST(CURRENT_DATE - INTERVAL '30' DAY AS TIMESTAMP)
      AND b.time_of_event < CAST(CURRENT_DATE + INTERVAL '1' DAY AS TIMESTAMP)
)
SELECT
    event_date_ist,
    COUNT(DISTINCT tin) AS total_tickets,
    SUM(seat_count) AS total_seats,
    SUM(COALESCE(ticket_fare, 0)) AS total_gmv,
    COUNT(DISTINCT CASE WHEN hft = 2 THEN tin END) AS total_primo_tickets,
    SUM(CASE WHEN hft = 2 THEN seat_count ELSE 0 END) AS total_primo_seats,
    SUM(CASE WHEN hft = 2 THEN COALESCE(ticket_fare, 0) ELSE 0 END) AS total_primo_gmv,
    COUNT(DISTINCT CASE WHEN seat_count >= 3 THEN tin END) AS tickets_seatcount_ge_3,
    SUM(CASE WHEN seat_count >= 3 THEN seat_count ELSE 0 END) AS seats_seatcount_ge_3,
    SUM(CASE WHEN seat_count >= 3 THEN COALESCE(ticket_fare, 0) ELSE 0 END) AS gmv_seatcount_ge_3,
    SUM(COALESCE(rb_sl_offer, 0)) AS discount
FROM base
GROUP BY
    event_date_ist
ORDER BY
    event_date_ist
