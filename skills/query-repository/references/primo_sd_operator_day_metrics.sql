svoc_users AS (
    SELECT DISTINCT
        TRY_CAST(rb_userid AS BIGINT) AS rb_user_id,
        TRY_CAST(age AS INTEGER) AS age,
        CASE
            WHEN LOWER(gender) IN ('male', 'm') THEN 'MALE'
            WHEN LOWER(gender) IN ('female', 'f') THEN 'FEMALE'
            ELSE 'UNKNOWN'
        END AS gender_class,
        CASE
            WHEN TRY_CAST(age AS INTEGER) BETWEEN 15 AND 27 THEN 'GENZ_15_27'
            WHEN TRY_CAST(age AS INTEGER) >= 60 THEN 'SR_CITIZEN_60_PLUS'
            ELSE 'OTHERS'
        END AS age_segment
    FROM svoc.svoc_booker
    WHERE rb_userid IS NOT NULL
      AND TRY_CAST(age AS INTEGER) <= 23
